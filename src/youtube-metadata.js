const { bestCoverThumbnail } = require('./artwork');
const { musicReference, selectMusicMatch } = require('./music-match');

const albumCovers = new Map();
const AUDIO_TRACK = 'MUSIC_VIDEO_TYPE_ATV';
const MUSIC_VIDEO = 'MUSIC_VIDEO_TYPE_OMV';

function text(value) {
    const content = typeof value === 'string' ? value : value?.text;
    return typeof content === 'string' ? content.trim() : '';
}

function musicTagsFromDetails(details) {
    // Require dedicated music fields, never the uploader or a guessed split of
    // the video title. Incomplete data still goes through the catalog lookup.
    const title = text(details?.track);
    let artist = [...new Set((Array.isArray(details?.artists) ? details.artists : [])
        .map(text).filter(Boolean))];
    if (!artist.length && text(details?.artist)) artist = [text(details.artist)];
    const album = text(details?.album);
    if (!title || !artist.length || !album) return null;

    // Music credits can describe a background song, or omit a live/remix
    // qualifier. Compare the video identity against the explicit song fields
    // using the same normalization and version rules as Music search.
    const video = musicReference(details);
    const song = musicReference({ ...details, title, track: title, artists: artist });
    if (!video || !song || video.title !== song.title || video.artists !== song.artists
        || video.versions !== song.versions) return null;

    // yt-dlp uses this description marker for auto-generated music releases.
    // Only their thumbnails represent release artwork; a normal music video's
    // thumbnail (even a square one) still needs a YouTube Music/Deezer lookup.
    if (!/\nAuto-generated by YouTube\.$/.test(text(details.description))) return null;
    // Require known, sufficient dimensions before skipping Music lookup.
    // This also excludes speculative thumbnail URLs generated by yt-dlp.
    // A tiny preview or unknown-size URL is still missing usable cover art.
    const cover = bestCoverThumbnail(details.thumbnails);
    if (!cover) return null;

    return { title, artist, album, cover, source: 'YouTube Music' };
}

function musicType(track) {
    if (track.item_type === 'song') return AUDIO_TRACK;
    return track.endpoint?.payload?.watchEndpointMusicSupportedConfigs?.watchEndpointMusicConfig?.musicVideoType;
}

function matchingTracks(queue, videoId) {
    const matches = new Map();
    for (const entry of queue?.contents || []) {
        const group = (entry?.type === 'PlaylistPanelVideoWrapper'
            ? [entry.primary, ...(entry.counterpart || [])] : [entry])
            .filter((track) => track?.type === 'PlaylistPanelVideo');
        if (!group.some((track) => track.video_id === videoId)) continue;
        for (const track of group) {
            // A wrapper explicitly links the music video to its audio release.
            // Never substitute an unrelated queue recommendation here.
            if (track.video_id === videoId || musicType(track) === AUDIO_TRACK) {
                matches.set(track.video_id, track);
            }
        }
    }
    return [...matches.values()].sort((a, b) =>
        Number(musicType(b) === AUDIO_TRACK) - Number(musicType(a) === AUDIO_TRACK));
}

async function trackTags(client, track, signal) {
    const type = musicType(track);
    if (type && ![AUDIO_TRACK, MUSIC_VIDEO].includes(type)) return null;
    const title = text(track.title);
    const artist = [...new Set((track.artists || [])
        .filter((entry) => entry.channel_id?.startsWith('UC'))
        .map((entry) => text(entry.name)).filter(Boolean))];
    // YouTube.js only parses linked artists from the long byline. On an
    // explicitly identified audio release, the short Music byline is also an
    // artist label. Do not use this fallback for videos or uploading channels.
    if (!artist.length && type === AUDIO_TRACK && text(track.author)) artist.push(text(track.author));
    const album = text(track.album?.name);
    const albumId = track.album?.id;
    const hasAlbum = albumId?.startsWith('MPR');
    // A catalog audio track can have valid song tags without an album field.
    // A video still needs a linked release; its thumbnail is not album artwork.
    if (!title || !artist.length || (type !== AUDIO_TRACK && !hasAlbum)) return null;

    const thumbnails = Array.isArray(track.thumbnail) ? track.thumbnail : track.thumbnails || [];
    // Only catalog audio thumbnails are release art. A video preview is never
    // a fallback cover, regardless of its dimensions.
    const artwork = type === AUDIO_TRACK && Array.isArray(thumbnails) ? [...thumbnails] : [];
    let cover = bestCoverThumbnail(artwork);
    if (!cover && hasAlbum) {
        try {
            let albumArtwork = albumCovers.get(albumId);
            if (!albumArtwork) {
                const release = await client.music.getAlbum(albumId);
                signal?.throwIfAborted();
                const images = release.header?.thumbnails || release.header?.thumbnail?.contents;
                albumArtwork = Array.isArray(images) ? images.filter((image) => image?.url) : [];
                if (albumArtwork.length) {
                    // Keep dimensions so a cached album preview cannot replace
                    // a larger track image. Reuse the result across playlists.
                    if (albumCovers.size >= 50) albumCovers.delete(albumCovers.keys().next().value);
                    albumCovers.set(albumId, albumArtwork);
                }
            }
            artwork.push(...albumArtwork);
        } catch (error) {
            signal?.throwIfAborted();
            // An optional quality upgrade must not discard valid music tags
            // and an existing cover if the album request fails.
            if (!bestCoverThumbnail(artwork, { allowSmall: true })) throw error;
            console.warn(`Could not load larger album artwork: ${error.message}`);
        }
        cover = bestCoverThumbnail(artwork);
    }
    // Some releases only provide small images. Use the largest known option
    // after trying the album, rather than losing the song's tags altogether.
    cover ||= bestCoverThumbnail(artwork, { allowSmall: true });
    if (!cover) return null;

    return { title, artist, album, cover, source: 'YouTube Music' };
}

async function lookupMusicTags(client, videoId, signal) {
    signal?.throwIfAborted();
    const queue = await client.music.getUpNext(videoId, false);
    signal?.throwIfAborted();
    const tracks = matchingTracks(queue, videoId);
    if (!tracks.length) {
        return { tags: null, reason: 'YouTube Music did not return this video or a linked music release.' };
    }

    let lookupError;
    const tryTrack = async (track) => {
        signal?.throwIfAborted();
        try {
            return await trackTags(client, track, signal);
        } catch (error) {
            signal?.throwIfAborted();
            lookupError = error;
            return null;
        }
    };
    for (const track of tracks) {
        const tags = await tryTrack(track);
        if (tags) return { tags };
    }

    // A video queue can carry only a small preview of its audio counterpart.
    // Fetch that exact linked release once to get its complete Music byline.
    const counterpart = tracks.find((track) => track.video_id !== videoId && musicType(track) === AUDIO_TRACK);
    if (counterpart) {
        signal?.throwIfAborted();
        const releaseQueue = await client.music.getUpNext(counterpart.video_id, false);
        signal?.throwIfAborted();
        const release = matchingTracks(releaseQueue, counterpart.video_id)
            .find((track) => track.video_id === counterpart.video_id);
        if (release) {
            const tags = await tryTrack(release);
            if (tags) return { tags };
        }
    }
    if (lookupError) throw lookupError;
    return { tags: null, reason: 'YouTube Music did not provide a song title, artist, and release artwork for this video.' };
}

async function searchMusicTags(client, details, signal) {
    signal?.throwIfAborted();
    const reference = musicReference(details);
    if (!reference) {
        return { tags: null, reason: 'The video did not provide enough artist, song, and duration information to verify a YouTube Music search match.' };
    }
    // Search only catalog songs. Read node types instead of the localized
    // "Songs" heading, and keep this to one page of at most twenty candidates.
    const results = await client.music.search(reference.query, { type: 'song' });
    signal?.throwIfAborted();
    const tracks = (results.contents || []).filter((section) => section.type === 'MusicShelf')
        .flatMap((section) => section.contents || []).slice(0, 20);
    const match = selectMusicMatch(reference, tracks);
    if (!match.track) return { tags: null, reason: match.reason };
    const tags = await trackTags(client, match.track, signal);
    signal?.throwIfAborted();
    return tags ? { tags } : { tags: null, reason: 'The matching YouTube Music release did not provide usable tags and artwork.' };
}

module.exports = { musicTagsFromDetails, lookupMusicTags, searchMusicTags };
